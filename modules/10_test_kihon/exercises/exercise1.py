def bytes_to_gb(size_bytes):
    """
    バイト数(int)を受け取り、GB(ギガバイト)単位のfloatに変換して返す。

    サーバーのディスク使用量やメモリ使用量は、OSのコマンド(dfコマンドなど)
    からバイト単位の数値として取得できることがよくあります。しかし人間が
    読むときは、GB単位に変換したほうがずっとわかりやすくなります。

    引数:
        size_bytes (int): バイト数。0以上の整数を想定。

    戻り値:
        float: GB単位に変換した値。小数点第2位までround(四捨五入)したもの。
               1GB = 1024 * 1024 * 1024 バイトとして計算する。

    入出力例:
        >>> bytes_to_gb(1073741824)
        1.0
        >>> bytes_to_gb(0)
        0.0
        >>> bytes_to_gb(536870912)
        0.5
    """
    gb = size_bytes / (1024 * 1024 * 1024)
    return round(gb, 2)
